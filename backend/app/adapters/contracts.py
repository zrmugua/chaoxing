from dataclasses import dataclass, field
from typing import Callable, Protocol


class AdapterError(Exception):
    """Sanitized integration error with a stable machine code."""
    def __init__(self, code: str, message: str, retryable: bool = False):
        super().__init__(message)
        self.code = code
        self.retryable = retryable


@dataclass
class Job:
    id: str
    chapter_id: str
    kind: str
    title: str
    passed: bool
    card: int
    metadata: dict = field(repr=False)
    defaults: dict = field(repr=False)


class ChaoxingAdapter(Protocol):
    def login(self, username: str, password: str) -> None: ...
    def list_courses(self) -> list[dict]: ...
    def list_chapters(self, course: dict) -> list[dict]: ...
    def list_jobs(self, course: dict, chapter: dict) -> list[Job]: ...
    def execute(self, course: dict, job: Job, control: Callable[[], None], progress: Callable[[float], None]) -> None: ...
    def questions(self, course: dict, job: Job) -> list[dict]: ...
    def export_cookies(self) -> list[dict]: ...
    def list_assessments(self, course: dict, work: bool = True, exam: bool = True) -> list[dict]: ...
    def chapter_paper(self, course: dict, job: Job) -> dict: ...
    def assessment_questions(self, course: dict, assessment: dict) -> dict: ...
    def save_answers(self, paper_id: str, answers: dict, submit: bool = False, require_complete: bool = False) -> dict: ...
    def chaoxing_answer(self, course: dict, question: dict) -> str: ...
    def close(self) -> None: ...
